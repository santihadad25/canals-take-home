-- Postgres runs the scripts in this folder once, the first time the database starts with an empty
-- data directory: the schema (this file), the demo data (02) and the database for the tests (03).

CREATE TABLE products (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name             TEXT   NOT NULL,
    unit_price_cents BIGINT NOT NULL,
    CONSTRAINT pk_products PRIMARY KEY (id),
    CONSTRAINT ck_products_unit_price_non_negative CHECK (unit_price_cents >= 0)
);

CREATE TABLE warehouses (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name      TEXT             NOT NULL,
    latitude  DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    CONSTRAINT pk_warehouses PRIMARY KEY (id),
    CONSTRAINT ck_warehouses_latitude_range CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_warehouses_longitude_range CHECK (longitude BETWEEN -180 AND 180)
);

CREATE TABLE stock (
    warehouse_id BIGINT  NOT NULL,
    product_id   BIGINT  NOT NULL,
    quantity     INTEGER NOT NULL,
    CONSTRAINT pk_stock PRIMARY KEY (warehouse_id, product_id),
    CONSTRAINT fk_stock_warehouse_id_warehouses FOREIGN KEY (warehouse_id) REFERENCES warehouses (id),
    CONSTRAINT fk_stock_product_id_products FOREIGN KEY (product_id) REFERENCES products (id),
    -- Whatever the code does, stock can never go negative.
    CONSTRAINT ck_stock_quantity_non_negative CHECK (quantity >= 0)
);

-- "Which warehouses hold these products?" starts from the product, so this index covers it.
CREATE INDEX ix_stock_product_id_warehouse_id ON stock (product_id, warehouse_id) INCLUDE (quantity);

CREATE TABLE orders (
    id                 UUID             NOT NULL,
    -- An id owned by another system: deliberately no foreign key.
    customer_id        TEXT             NOT NULL,
    idempotency_key    UUID             NOT NULL,
    request_hash       VARCHAR(64)      NOT NULL,
    shipping_address   TEXT             NOT NULL,
    shipping_latitude  DOUBLE PRECISION NOT NULL,
    shipping_longitude DOUBLE PRECISION NOT NULL,
    warehouse_id       BIGINT           NOT NULL,
    status             VARCHAR(32)      NOT NULL,
    total_cents        BIGINT           NOT NULL,
    payment_id         TEXT,
    failure_code       TEXT,
    expires_at         TIMESTAMPTZ      NOT NULL,
    created_at         TIMESTAMPTZ      NOT NULL,
    updated_at         TIMESTAMPTZ      NOT NULL,
    -- The lease a reconciler instance takes while it works on the order, so that several
    -- instances split the work instead of repeating each other's calls to the payment provider.
    claimed_until      TIMESTAMPTZ,
    CONSTRAINT pk_orders PRIMARY KEY (id),
    CONSTRAINT uq_orders_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT fk_orders_warehouse_id_warehouses FOREIGN KEY (warehouse_id) REFERENCES warehouses (id),
    CONSTRAINT ck_orders_status_valid CHECK (
        status IN ('PENDING', 'AUTHORIZED', 'PAID', 'PAYMENT_FAILED', 'PAYMENT_UNKNOWN', 'EXPIRED')
    ),
    CONSTRAINT ck_orders_total_non_negative CHECK (total_cents >= 0)
);

CREATE INDEX ix_orders_customer_id ON orders (customer_id);

-- Two small indexes for the reconciler: they only contain the orders that are still open.
CREATE INDEX ix_orders_unpaid_expires_at ON orders (expires_at)
    WHERE status IN ('PENDING', 'PAYMENT_UNKNOWN');
CREATE INDEX ix_orders_authorized_updated_at ON orders (updated_at)
    WHERE status = 'AUTHORIZED';

CREATE TABLE order_items (
    order_id         UUID    NOT NULL,
    product_id       BIGINT  NOT NULL,
    quantity         INTEGER NOT NULL,
    unit_price_cents BIGINT  NOT NULL,
    CONSTRAINT pk_order_items PRIMARY KEY (order_id, product_id),
    CONSTRAINT fk_order_items_order_id_orders FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT fk_order_items_product_id_products FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_order_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_order_items_unit_price_non_negative CHECK (unit_price_cents >= 0)
);

-- Append-only history, written in the same transaction as every status change.
CREATE TABLE order_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id    UUID        NOT NULL,
    from_status VARCHAR(32),
    to_status   VARCHAR(32) NOT NULL,
    detail      TEXT,
    created_at  TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_order_events PRIMARY KEY (id),
    CONSTRAINT fk_order_events_order_id_orders FOREIGN KEY (order_id) REFERENCES orders (id)
);

CREATE INDEX ix_order_events_order_id ON order_events (order_id);
